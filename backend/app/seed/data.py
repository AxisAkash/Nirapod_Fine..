DATASET_DESCRIPTION = "Built from the Road Transport Act 2018 fines guide and the exceptions and exemptions guide."

SOURCE_FILES = [
    "Bangladesh_Road_Transport_Act_2018_Traffic_Fines.pdf",
    "Bangladesh_Traffic_Law_Exceptions_and_Exemptions.pdf",
]

FINES_REF = "Road Transport Act 2018, s.{section} (fines guide)"


def _rule(
    section,
    offence,
    category,
    fine_text,
    aliases,
    bn,
    keywords,
    *,
    max_fine,
    min_fine=0,
    imprisonment=None,
    repeat=None,
    matchable=True,
    fine_tiers=None,
):
    return {
        "section": section,
        "title": offence,
        "description": offence,
        "category": category,
        "min_fine": min_fine,
        "max_fine": max_fine,
        "fine_text": fine_text,
        "imprisonment_text": imprisonment,
        "repeat_rule_text": repeat,
        "source_reference": FINES_REF.format(section=section),
        "aliases": [{"text": a, "language": "en"} for a in aliases]
        + [{"text": a, "language": "bn"} for a in bn],
        "keywords": [{"word": w, "weight": wt} for w, wt in keywords],
        "matchable": matchable,
        "fine_tiers": fine_tiers or [],
    }


