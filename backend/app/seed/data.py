"""Structured legal dataset derived from the two source PDFs in data/source/.

Offence rules   <- Bangladesh_Road_Transport_Act_2018_Traffic_Fines.pdf   (sections 66-105)
Exception rules <- Bangladesh_Traffic_Law_Exceptions_and_Exemptions.pdf

Amounts are in BDT (Taka); 1 lakh = 100,000. ``max_fine=None`` means the source states no numeric
ceiling, so the engine must send such cases to manual review instead of guessing.
Bangla aliases are included because receipts are usually written in Bangla.
"""

LAKH = 100_000

